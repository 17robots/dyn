#!/usr/bin/env python3
"""Execute generated ARM64 memory routines on native ARM or QEMU.

Clang supplies a C ABI oracle caller only when cross-executing under QEMU;
all tested instructions/relocations are generated by native-runtime.py.
"""
import ast
import importlib.util
import os
from pathlib import Path
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DYN = Path(os.environ.get('DYN', ROOT / 'build/dyn')).resolve()
arm = platform.system() == 'Linux' and platform.machine().lower() in ('aarch64', 'arm64')
qemu = shutil.which('qemu-aarch64')
clang = shlex.split(os.environ.get('CLANG', 'clang'))
if not arm and (not qemu or not shutil.which(clang[0])):
    print('SKIP ARM memory execution: needs native ARM Linux or QEMU + oracle Clang')
    raise SystemExit(0)
spec = importlib.util.spec_from_file_location('native_runtime', ROOT / 'tools/native-runtime.py')
runtime = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = runtime
spec.loader.exec_module(runtime)
for node in ast.parse((ROOT / 'tests/cross-runtime.py').read_text()).body:
    if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'HARNESS' for t in node.targets):
        harness = ast.literal_eval(node.value)
        break
else:
    raise AssertionError('missing shared memory behavior fixture')


def run(args, **kwargs):
    p = subprocess.run(list(map(str, args)), text=True, capture_output=True, timeout=90, **kwargs)
    assert p.returncode == 0, (args, p.stdout, p.stderr)


with tempfile.TemporaryDirectory(prefix='dyn-arm-memory-') as temporary:
    root = Path(temporary)
    assembler = runtime.Assembler('aarch64-linux').assemble(ROOT / 'runtime/native_memory_aarch64.S')
    aliases = {'memcpy': 'rt_copy', 'memmove': 'rt_move', 'memset': 'rt_fill'}
    assembler.symbols = {aliases.get(k, k): v for k, v in assembler.symbols.items()}
    assembler.globals = {aliases.get(k, k) for k in assembler.globals}
    assembler.hidden = {aliases.get(k, k) for k in assembler.hidden}
    memory = root / 'memory.o'; memory.write_bytes(assembler.object())
    source = root / 'oracle.c'
    output = root / 'memory-test'
    if arm:
        source.write_text(harness)
        run([*shlex.split(os.environ.get('CC', 'cc')), '-O2', '-fno-builtin', source, memory, '-o', output])
        run([output])
    else:
        text = re.sub(r'^#include.*$', '', harness, flags=re.M)
        text = text.replace('int main(void)', 'int audit_memory(void)').replace(
            'puts("PASS memory counts, alignment, overlap, return pointers, ABI");', '')
        source.write_text('typedef unsigned long size_t;\n#define NULL ((void*)0)\n#define abort() __builtin_trap()\n' + text)
        oracle = root / 'oracle.o'
        run([*clang, '--target=aarch64-linux-gnu', '-O2', '-ffreestanding', '-fno-builtin',
             '-fno-stack-protector', '-c', source, '-o', oracle])
        project = root / 'project'; project.mkdir()
        (project / 'main.dyn').write_text('extern fn audit_memory() i32\nfn main() { if audit_memory() != 0 { #panic("memory oracle") } }\n')
        run([DYN, 'build', project, '--target', 'aarch64-linux', '--backend', 'native',
             '--release', '--no-cache', '--link', memory, '--link', oracle, '--output', output],
            env=dict(os.environ, DYN_SDK=str(ROOT), DYN_LINKER='builtin'))
        run([qemu, output])
print('PASS generated ARM64 memory: 0..1024-byte copies/fills, both overlap directions, every offset 0..17, return values')
