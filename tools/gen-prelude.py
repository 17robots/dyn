#!/usr/bin/env python3
"""Embeds src/prelude.dyn, the declarations the compiler adds in front of a
program that uses #typeof or a math builtin, as src/prelude.inc.
--check exits 1 when src/prelude.inc is out of date."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/prelude.dyn'
OUTPUT = ROOT / 'src/prelude.inc'

def generate():
    # One literal per line: ISO C caps a single string literal at 4095 bytes.
    lines = ['/* Generated by tools/gen-prelude.py from src/prelude.dyn; edit that file. */',
             'static const char *const compiler_prelude[] = {']
    for line in SOURCE.read_text().splitlines():
        lines.append('    ' + json.dumps(line + '\n') + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'

text = generate()
if sys.argv[1:] == ['--check']:
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        print('src/prelude.inc is out of date: run tools/gen-prelude.py')
        raise SystemExit(1)
    print('PASS prelude: src/prelude.inc matches src/prelude.dyn')
else:
    OUTPUT.write_text(text)
