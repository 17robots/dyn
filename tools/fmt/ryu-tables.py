#!/usr/bin/env python3
"""Regenerate std/fmt/ryu_tables.dyn from Ryu's table formulas.

Pass Ryu's d2s_full_table.h to check the result against the upstream table.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
MASK = (1 << 64) - 1


def pow5_bits(e):
    return ((e * 1217359) >> 19) + 1


def pow5(i):
    shift = pow5_bits(i) - 125
    return 5 ** i >> shift if shift >= 0 else 5 ** i << -shift


def pow5_inverse(i):
    return (1 << (pow5_bits(i) - 1 + 125)) // 5 ** i + 1


def emit(name, values):
    lines = []
    for part, pick in (('low', lambda v: v & MASK), ('high', lambda v: v >> 64)):
        rows = [', '.join(str(pick(v)) for v in values[i:i + 4]) for i in range(0, len(values), 4)]
        lines.append(f'const {name}_{part}: [{len(values)}]u64 = [')
        lines.append(',\n'.join('  ' + row for row in rows))
        lines.append(']')
    return '\n'.join(lines)


inverse = [pow5_inverse(i) for i in range(342)]
forward = [pow5(i) for i in range(326)]
if len(sys.argv) > 1:
    header = Path(sys.argv[1]).read_text()
    for name, values in (('DOUBLE_POW5_INV_SPLIT', inverse), ('DOUBLE_POW5_SPLIT[', forward)):
        body = header[header.index(name):]
        body = body[body.index('{') + 1:body.index('};')]
        numbers = [int(x) for x in re.findall(r'(\d+)u', body)]
        assert [numbers[i] | numbers[i + 1] << 64 for i in range(0, len(numbers), 2)] == values, name
(ROOT / 'std/fmt/ryu_tables.dyn').write_text(
    '// Generated by tools/fmt/ryu-tables.py from Ryu\'s formulas; checked\n'
    '// against the upstream d2s_full_table.h. Do not edit.\n'
    + emit('pow5_inverse', inverse) + '\n' + emit('pow5', forward) + '\n')
