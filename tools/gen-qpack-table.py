#!/usr/bin/env python3
"""Writes std/net/http/qpack/tables.dyn: the QPACK static table (RFC 9204
Appendix A), read from the RFC text. Usage: tools/gen-qpack-table.py rfc9204.txt
(https://www.rfc-editor.org/rfc/rfc9204.txt)."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
lines = Path(sys.argv[1]).read_text().split('\n')
start = next(i for i, line in enumerate(lines) if line.startswith('Appendix A.  Static Table'))
rows, current = [], None
for line in lines[start:]:
    text = line.strip()
    if text.startswith('Appendix B'):
        break
    if text.startswith('+-') or text.startswith('+='):
        if current:
            rows.append(current)
        current = None
        continue
    if text.startswith('|'):
        cells = [cell.strip() for cell in text.strip('|').split('|')]
        if cells[0] == 'Index':
            continue
        if current is None:
            current = [[cell] for cell in cells]
        else:
            for k, cell in enumerate(cells):
                current[k].append(cell)


def join(pieces):
    # The RFC wraps long cells; a piece ending in ';' continued after a space.
    out = ''
    for piece in (p for p in pieces if p):
        out += (' ' if out.endswith(';') else '') + piece
    return out


entries = [(int(join(r[0])), join(r[1]), join(r[2])) for r in rows]
assert [e[0] for e in entries] == list(range(99)), 'indexes 0-98 in order'
text, spans = '', []
for _, name, value in entries:
    spans.append((len(text), len(name), len(text) + len(name), len(value)))
    text += name + value


def array(name, kind, values):
    lines = [', '.join(str(v) for v in values[i:i + 16]) for i in range(0, len(values), 16)]
    return 'const %s: [%d]%s = [\n  %s,\n]\n' % (name, len(values), kind, ',\n  '.join(lines))


out = ['// Generated by tools/gen-qpack-table.py from RFC 9204 Appendix A.', '']
out.append('const StaticText: []const u8 = "%s"\n' % text.replace('\\', '\\\\').replace('"', '\\"'))
out.append(array('StaticNameStart', 'u16', [s[0] for s in spans]))
out.append(array('StaticNameLength', 'u8', [s[1] for s in spans]))
out.append(array('StaticValueStart', 'u16', [s[2] for s in spans]))
out.append(array('StaticValueLength', 'u8', [s[3] for s in spans]))
(ROOT / 'std/net/http/qpack/tables.dyn').write_text('\n'.join(out))
print('wrote std/net/http/qpack/tables.dyn: %d entries' % len(entries))
