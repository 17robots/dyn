#!/usr/bin/env python3
"""Writes docs/guide/std-index.md: every public declaration in std, one line
each, grouped by module, from `dyn docs --json`. --check exits 1 when the
committed index is out of date."""
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DYN = str(Path(os.environ.get('DYN', ROOT / 'build/dyn-release')).resolve())
OUTPUT = ROOT / 'docs/guide/std-index.md'
KINDS = {'function': 'fn', 'struct': 'struct', 'enum': 'enum', 'alias': 'type', 'constant': 'const', 'variable': 'var'}


def summary(comments):
    """The first sentence of a declaration's comment, on one line."""
    text = ' '.join(line.strip().lstrip('/').strip() for line in comments.splitlines()).strip()
    for end in ('. ', '; '):
        if end in text:
            text = text[:text.index(end) + 1]
    if len(text) > 140:
        text = text[:140].rsplit(' ', 1)[0].rstrip(',;:') + ' ...'
    return text


def module_lines(directory):
    relative = directory.relative_to(ROOT).as_posix()
    result = subprocess.run([DYN, 'docs', '--json', relative], cwd=ROOT, capture_output=True, text=True, timeout=120,
                            env={**os.environ, 'DYN_SDK': str(ROOT)})
    if result.returncode:
        raise SystemExit(f'dyn docs {relative} failed:\n{result.stderr}')
    lines, seen = [], set()
    for source in json.loads(result.stdout)['files']:
        for declaration in source['declarations']:
            text = ' '.join(declaration['declaration'].split())
            if text.startswith('pub '):
                text = text[4:]
            # Per-target files repeat a declaration; list it once.
            if text in seen:
                continue
            seen.add(text)
            note = summary(declaration.get('source_comments', ''))
            lines.append(f'- `{text}`' + (f': {note}' if note else ''))
    return relative, lines


def layers():
    found = {}
    for line in (ROOT / 'std/layers.txt').read_text().splitlines():
        if line.strip() and not line.startswith('#'):
            layer, module = line.split()
            found[module] = layer
    return found


def generate():
    modules = sorted({path.parent for path in (ROOT / 'std').rglob('*.dyn')})
    layer_of = layers()
    out = ['# Standard library index', '',
           'Every public declaration in `std`, grouped by module. Generated by `tools/std-index.py` from',
           '`dyn docs --json`; run it after changing a public declaration. `dyn docs std/<module>` prints a',
           "module's full declarations and comments. Each module names its layer (see `std/layers.txt`):",
           'core and heap build on every target, bare metal included; std needs an operating system.', '']
    for directory in modules:
        name, lines = module_lines(directory)
        if not lines:
            continue
        out += [f'## {name}', '', f'Layer: {layer_of.get(name, "std")}', '', *lines, '']
    return '\n'.join(out)


text = generate()
if sys.argv[1:] == ['--check']:
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        print('docs/guide/std-index.md is out of date: run tools/std-index.py')
        raise SystemExit(1)
    print('PASS std index: docs/guide/std-index.md matches std')
else:
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT.relative_to(ROOT)}: {text.count(chr(10) + "- ")} declarations')
