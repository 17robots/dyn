#!/usr/bin/env python3
"""Writes std/net/http/hpack/tables.dyn: the HPACK static table (RFC 7541
Appendix A) and Huffman code (Appendix B), read from Go's vendored copy of
golang.org/x/net/http2/hpack. Usage: tools/gen-hpack-tables.py GOROOT"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]) / 'src/vendor/golang.org/x/net/http2/hpack'
tables = (source / 'tables.go').read_text()
static = (source / 'static_table.go').read_text()


def array(name):
    body = re.search(r'var %s = \[256\]uint(?:8|32)\{(.*?)\n\}' % name, tables, re.S).group(1)
    return [int(value, 0) for value in re.findall(r'0x[0-9a-f]+|\b\d+\b', body)]


codes, lengths = array('huffmanCodes'), array('huffmanCodeLen')
assert len(codes) == len(lengths) == 256
# EOS (RFC 7541 Appendix B): 30 ones. Decoding never yields it.
order = sorted(range(257), key=lambda s: ((lengths + [30])[s], (codes + [0x3fffffff])[s]))
all_codes, all_lengths = codes + [0x3fffffff], lengths + [30]
first_code, first_index, count = [0] * 31, [0] * 31, [0] * 31
code = 0
previous = 0
for index, symbol in enumerate(order):
    length = all_lengths[symbol]
    code <<= length - previous
    previous = length
    assert all_codes[symbol] == code, ('not canonical', symbol)
    if count[length] == 0:
        first_code[length], first_index[length] = code, index
    count[length] += 1
    code += 1
entries = re.findall(r'\{Name: "([^"]*)", Value: "([^"]*)", Sensitive: false\}', static)
assert len(entries) == 61
text, starts = '', []
for name, value in entries:
    starts.append((len(text), len(name), len(text) + len(name), len(value)))
    text += name + value


def dyn_array(name, kind, values, per_line=16):
    lines = [', '.join(str(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return 'const %s: [%d]%s = [\n  %s,\n]\n' % (name, len(values), kind, ',\n  '.join(lines))


out = ['// Generated by tools/gen-hpack-tables.py from golang.org/x/net/http2/hpack.',
       '// HPACK static table (RFC 7541 Appendix A) and Huffman code (Appendix B).', '']
out.append('const StaticText: []const u8 = "%s"\n' % text)
out.append(dyn_array('StaticNameStart', 'u16', [s[0] for s in starts]))
out.append(dyn_array('StaticNameLength', 'u8', [s[1] for s in starts]))
out.append(dyn_array('StaticValueStart', 'u16', [s[2] for s in starts]))
out.append(dyn_array('StaticValueLength', 'u8', [s[3] for s in starts]))
out.append(dyn_array('HuffmanCodes', 'u32', codes, 8))
out.append(dyn_array('HuffmanLengths', 'u8', lengths))
out.append('// Canonical decoding: codes of each length are consecutive from\n'
           '// FirstCode, naming symbols DecodeSymbols[FirstIndex..]; index 256 is EOS.')
out.append(dyn_array('DecodeSymbols', 'u16', order))
out.append(dyn_array('FirstCode', 'u32', first_code, 8))
out.append(dyn_array('FirstIndex', 'u16', first_index))
out.append(dyn_array('LengthCount', 'u16', count))
(ROOT / 'std/net/http/hpack/tables.dyn').write_text('\n'.join(out))
print('wrote std/net/http/hpack/tables.dyn')
