#!/usr/bin/env python3
"""Embeds the guide pages `dyn guide` prints as src/guide.inc, so an installed
compiler shows the guide that matches it without the docs on disk.
--check exits 1 when src/guide.inc is out of date."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/guide.inc'
# Topic, page and one line for the topic list, in the order `dyn guide` lists them.
TOPICS = [
    ('brief', 'brief.md', 'one page: work loop, program shape, failure, memory'),
    ('rules', 'rules.md', 'every language rule, numbered'),
    ('idioms', 'idiomatic-dyn.md', 'how to write clear, correct Dyn'),
    ('language', 'language.md', 'the language reference'),
    ('memory', 'memory.md', 'arenas, lifetimes and handles'),
    ('collections', 'collections.md', 'arrays, lists, maps and handles on arenas'),
    ('std', 'std.md', 'the standard library and its conventions'),
    ('style', 'style.md', 'layout and naming'),
    ('agent', 'agent-guide.md', 'tooling for agents: docs, query, diagnostics'),
]

def generate():
    # One literal per line: ISO C caps a single string literal at 4095 bytes.
    lines = ['/* Generated by tools/gen-guide.py from docs/guide; edit those pages. */']
    for index, (topic, page, _) in enumerate(TOPICS):
        lines.append(f'static const char *const guide_page_{index}[] = {{')
        for line in (ROOT / 'docs/guide' / page).read_text().splitlines():
            lines.append('    ' + json.dumps(line + '\n') + ',')
        lines.append('    0,')
        lines.append('};')
    lines.append('static const struct { const char *topic, *summary; const char *const *page; } guide_topics[] = {')
    for index, (topic, _, summary) in enumerate(TOPICS):
        lines.append(f'    {{{json.dumps(topic)}, {json.dumps(summary)}, guide_page_{index}}},')
    lines.append('};')
    return '\n'.join(lines) + '\n'

text = generate()
if sys.argv[1:] == ['--check']:
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        print('src/guide.inc is out of date: run tools/gen-guide.py')
        raise SystemExit(1)
    print('PASS guide: src/guide.inc matches docs/guide')
else:
    OUTPUT.write_text(text)
