const Token = struct {
    k: TokenKind,
    v: []const u8,
    l: isize,
    c: isize,
};

fn token_to_string(kind: TokenKind) []const u8 {
    return TokenStrings[@intFromEnum(kind)];
}

fn precedence(t: Token) i32 {
    return switch (t.kind) {
        .oror => 1,
        .andand => 2,
        .eqeq, .noteq, .lt, .gt, .lteq, .gteq => 3,
        .add, .sub, .@"or", .xor => 4,
        .mul, .div, .mod, .@"and" => 5,
        _ => 0,
    };
}
